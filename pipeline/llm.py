"""Thin wrapper around the LLM used by every agent.

Provider priority, decided once at import time from whatever's configured:

  1. OpenAI (OPENAI_API_KEY) — real structured outputs via
     response_format={"type": "json_schema", ...}, schema enforced
     server-side (strict mode).
  2. Groq (GROQ_API_KEY) — a free-tier fallback for testing without an
     OpenAI key. Groq's json_object mode only guarantees syntactically
     valid JSON, not conformance to our schema, so the schema is spelled
     out in the prompt and the result is validated against `required`
     before being trusted.
  3. Stub — if neither key is set, every call degrades to a clearly
     labelled placeholder instead of raising, so the pipeline can still be
     run end-to-end. Stub output never claims to be a real recommendation
     — see STUB_NOTE.

Every provider call is wrapped so a transient failure (rate limit, bad
request, bad JSON) falls back to the stub for that one call instead of
crashing the run.
"""
from __future__ import annotations

import json

from . import config

STUB_NOTE = (
    "LLM stub — either no OPENAI_API_KEY/GROQ_API_KEY is set, or the live call "
    "failed (see the console log for this run), so this value was generated by a "
    "placeholder, not a real model."
)

PROVIDER = "stub"
if config.OPENAI_API_KEY:
    PROVIDER = "openai"
elif config.GROQ_API_KEY:
    PROVIDER = "groq"

_client = None


def is_live() -> bool:
    return PROVIDER != "stub"


def provider_label() -> str:
    if PROVIDER == "openai":
        return f"OpenAI ({config.LLM_MODEL})"
    if PROVIDER == "groq":
        return f"Groq ({config.GROQ_MODEL}, free tier)"
    return "stub (no API key)"


def _get_client():
    global _client
    if _client is not None:
        return _client
    if PROVIDER == "openai":
        import openai
        _client = openai.OpenAI(api_key=config.OPENAI_API_KEY)
    elif PROVIDER == "groq":
        import groq
        _client = groq.Groq(api_key=config.GROQ_API_KEY)
    return _client


def _schema_as_instructions(schema: dict) -> str:
    """Render a JSON Schema into a plain-text field spec for providers (Groq)
    that don't enforce the schema server-side, so the prompt carries it."""
    props = schema.get("properties", {})
    required = set(schema.get("required", []))
    lines = []
    for name, spec in props.items():
        bits = [spec.get("type", "any")]
        if "enum" in spec:
            bits.append("one of " + ", ".join(repr(v) for v in spec["enum"]))
        if spec.get("description"):
            bits.append(spec["description"])
        mark = "required" if name in required else "optional"
        lines.append(f'  - "{name}" ({mark}, {" — ".join(bits)})')
    return "\n".join(lines)


def _stub(stub_factory) -> tuple[dict, bool]:
    stub = stub_factory() if stub_factory else {}
    if isinstance(stub, dict):
        stub.setdefault("_stub", True)
        stub.setdefault("_stub_note", STUB_NOTE)
    return stub, False


def _call_openai(system: str, user: str, schema: dict, max_tokens: int):
    import openai
    client = _get_client()
    try:
        response = client.chat.completions.create(
            model=config.LLM_MODEL,
            max_completion_tokens=max_tokens,
            messages=[
                {"role": "system", "content": system},
                {"role": "user", "content": user},
            ],
            response_format={"type": "json_schema", "json_schema": {
                "name": "output", "strict": True, "schema": schema,
            }},
        )
    except openai.RateLimitError as e:
        print(f"[llm:openai] rate limited, falling back to stub for this call: {e}")
        return None
    except openai.APIStatusError as e:
        print(f"[llm:openai] API error ({e.status_code}), falling back to stub for this call: {e.message}")
        return None
    except openai.APIConnectionError as e:
        print(f"[llm:openai] connection error, falling back to stub for this call: {e}")
        return None

    choice = response.choices[0]
    if choice.finish_reason == "content_filter":
        print("[llm:openai] model refused this request, falling back to stub for this call")
        return None
    if choice.finish_reason == "length":
        print(f"[llm:openai] output truncated (hit max_tokens={max_tokens}), falling back to stub for this call")
        return None
    text = choice.message.content
    if not text:
        print("[llm:openai] empty response, falling back to stub for this call")
        return None
    try:
        return json.loads(text)
    except json.JSONDecodeError as e:
        print(f"[llm:openai] response was not valid JSON ({e}), falling back to stub for this call")
        return None


def _call_groq(system: str, user: str, schema: dict, max_tokens: int):
    import groq
    client = _get_client()
    field_spec = _schema_as_instructions(schema)
    full_system = (
        f"{system}\n\n"
        "Respond with ONLY a single JSON object (no markdown fences, no commentary) "
        f"with exactly these fields:\n{field_spec}"
    )
    try:
        response = client.chat.completions.create(
            model=config.GROQ_MODEL,
            max_completion_tokens=max_tokens,
            messages=[
                {"role": "system", "content": full_system},
                {"role": "user", "content": user},
            ],
            response_format={"type": "json_object"},
        )
    except groq.RateLimitError as e:
        print(f"[llm:groq] rate limited (free-tier cap?), falling back to stub for this call: {e}")
        return None
    except groq.APIStatusError as e:
        print(f"[llm:groq] API error ({e.status_code}), falling back to stub for this call: {e.message}")
        return None
    except groq.APIConnectionError as e:
        print(f"[llm:groq] connection error, falling back to stub for this call: {e}")
        return None

    choice = response.choices[0]
    if choice.finish_reason == "length":
        print(f"[llm:groq] output truncated (hit max_tokens={max_tokens}), falling back to stub for this call")
        return None
    text = choice.message.content
    if not text:
        print("[llm:groq] empty response, falling back to stub for this call")
        return None
    try:
        data = json.loads(text)
    except json.JSONDecodeError as e:
        print(f"[llm:groq] response was not valid JSON ({e}), falling back to stub for this call")
        return None

    missing = [f for f in schema.get("required", []) if f not in data]
    if missing:
        print(f"[llm:groq] response is missing required field(s) {missing}, falling back to stub for this call")
        return None
    return data


def json_call(system: str, user: str, schema: dict, *, max_tokens: int = 4096,
              stub_factory=None) -> tuple[dict, bool]:
    """Call the configured LLM and return (parsed_json, was_live).

    `schema` is a JSON Schema object (no $schema/$id needed) describing the
    exact shape we want back. `stub_factory` is a zero-arg callable
    returning a dict shaped like the schema, used whenever no provider is
    configured or the live call fails for any reason.
    """
    if PROVIDER == "openai":
        data = _call_openai(system, user, schema, max_tokens)
    elif PROVIDER == "groq":
        data = _call_groq(system, user, schema, max_tokens)
    else:
        data = None

    if data is None:
        return _stub(stub_factory)
    return data, True
